// 진단 결과창(Analysis) 상단에 띄워줄 공식 텍스트 반환
export const getSkinDescription = (userTypeStr) => {
    const data = SKIN_TYPES[userTypeStr];
    if (!data) return "데이터 분석 중입니다.";
    return typeof data === 'string' ? data : data.description;
};

// 피부 타입 전체 데이터 반환 (description + characteristic + careDirection)
export const getSkinTypeData = (userTypeStr) => {
    const data = SKIN_TYPES[userTypeStr];
    if (!data) return { description: "데이터 분석 중입니다.", characteristic: '', careDirection: '' };
    return typeof data === 'string'
        ? { description: data, characteristic: '', careDirection: '' }
        : data;
};

// 핵심 로직: 상세 피부 타입(예: '지성 · 과민')에서 핵심(지성)을 뽑아 화장품을 매칭
export const getRecommendedProducts = (userTypeStr) => {
    if (!userTypeStr) return [];

    // 1. 유저의 상세 결과에서 메인 타입(건성, 수부지, 지성, 복합성, 중성) 추출
    let mainType = "중성";
    if (userTypeStr.includes("건성")) mainType = "건성";
    else if (userTypeStr.includes("수부지")) mainType = "수부지";
    else if (userTypeStr.includes("지성")) mainType = "지성";
    else if (userTypeStr.includes("복합성")) mainType = "복합성";

    // 2. productsData.js 의 ALL_PRODUCTS 중에서 해당 타입용 화장품만 쏙 뽑아서 반환!
    return ALL_PRODUCTS.filter(product => product.skinType === mainType);
};
